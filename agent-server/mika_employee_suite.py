class EmployeeWorkbookEngine:
    """Creates polished Excel (.xlsx) workbooks with formulas and professional formatting."""

    @staticmethod
    def create_tour_budget_model(output_path: str, title: str = "Georgia Tours 2027 - Financial & Budget Model") -> str:
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Tour Financials 2027"
        ws.views.sheetView[0].showGridLines = True

        # Styles
        header_fill = PatternFill(start_color="1F2937", end_color="1F2937", fill_type="solid")
        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        accent_fill = PatternFill(start_color="EEF2FF", end_color="EEF2FF", fill_type="solid")
        total_fill = PatternFill(start_color="F3F4F6", end_color="F3F4F6", fill_type="solid")
        bold_font = Font(name="Calibri", size=11, bold=True)
        title_font = Font(name="Calibri", size=16, bold=True, color="1E3A8A")
        sub_font = Font(name="Calibri", size=10, italic=True, color="6B7280")

        thin_border = Border(
            left=Side(style='thin', color='E5E7EB'),
            right=Side(style='thin', color='E5E7EB'),
            top=Side(style='thin', color='E5E7EB'),
            bottom=Side(style='thin', color='E5E7EB')
        )
        total_border = Border(
            top=Side(style='thin', color='1F2937'),
            bottom=Side(style='double', color='1F2937')
        )

        # Title Block
        ws['A1'] = title
        ws['A1'].font = title_font
        ws['A2'] = f"Generated by Mika AI Employee & Antigravity (AGY) • Date: {time.strftime('%Y-%m-%d')}"
        ws['A2'].font = sub_font

        headers = ["Package Name", "Duration (Days)", "Target Group Size", "Cost per Pax ($)", "Retail Price ($)", "Total Revenue ($)", "Total Cost ($)", "Gross Margin ($)", "Margin (%)"]
        
        row_idx = 4
        for col_idx, h in enumerate(headers, 1):
            cell = ws.cell(row=row_idx, column=col_idx, value=h)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center" if col_idx > 1 else "left", vertical="center", wrap_text=True)

        tours_data = [
            ("Grand Georgia 2027 (Kakheti + Kazbegi + Batumi)", 10, 14, 1350, 2690),
            ("Wine & Gourmet VIP Odyssey (Kakheti & Tbilisi)", 6, 8, 1100, 2250),
            ("Caucasus Mountains Trek (Svaneti & Truso)", 7, 10, 850, 1750),
            ("Tbilisi Arts, Architecture & Historic Baths", 4, 12, 480, 990),
            ("Black Sea & Adjara Cultural Escape", 5, 10, 620, 1350),
        ]

        start_row = 5
        for item in tours_data:
            name, days, group, cost, price = item
            ws.cell(row=start_row, column=1, value=name).font = Font(name="Calibri", size=11)
            ws.cell(row=start_row, column=2, value=days).alignment = Alignment(horizontal="center")
            ws.cell(row=start_row, column=3, value=group).alignment = Alignment(horizontal="center")
            
            c_cost = ws.cell(row=start_row, column=4, value=cost)
            c_cost.number_format = '$#,##0'
            
            c_price = ws.cell(row=start_row, column=5, value=price)
            c_price.number_format = '$#,##0'
            
            # Formulas
            c_rev = ws.cell(row=start_row, column=6, value=f"=C{start_row}*E{start_row}")
            c_rev.number_format = '$#,##0'
            
            c_tot_cost = ws.cell(row=start_row, column=7, value=f"=C{start_row}*D{start_row}")
            c_tot_cost.number_format = '$#,##0'
            
            c_margin = ws.cell(row=start_row, column=8, value=f"=F{start_row}-G{start_row}")
            c_margin.number_format = '$#,##0'
            c_margin.font = bold_font
            
            c_pct = ws.cell(row=start_row, column=9, value=f"=H{start_row}/F{start_row}")
            c_pct.number_format = '0.0%'
            
            for c in range(1, 10):
                ws.cell(row=start_row, column=c).border = thin_border
            start_row += 1

        # Summary / Totals Row
        ws.cell(row=start_row, column=1, value="Total / Portfolio Average").font = bold_font
        ws.cell(row=start_row, column=1).fill = total_fill
        ws.cell(row=start_row, column=2, value=f"=AVERAGE(B5:B{start_row-1})").alignment = Alignment(horizontal="center")
        ws.cell(row=start_row, column=2).number_format = '0.0'
        ws.cell(row=start_row, column=3, value=f"=SUM(C5:C{start_row-1})").alignment = Alignment(horizontal="center")
        ws.cell(row=start_row, column=4, value=f"=AVERAGE(D5:D{start_row-1})").number_format = '$#,##0'
        ws.cell(row=start_row, column=5, value=f"=AVERAGE(E5:E{start_row-1})").number_format = '$#,##0'
        
        c_tot_rev = ws.cell(row=start_row, column=6, value=f"=SUM(F5:F{start_row-1})")
        c_tot_rev.number_format = '$#,##0'
        c_tot_rev.font = bold_font
        
        c_tot_c = ws.cell(row=start_row, column=7, value=f"=SUM(G5:G{start_row-1})")
        c_tot_c.number_format = '$#,##0'
        c_tot_c.font = bold_font
        
        c_tot_m = ws.cell(row=start_row, column=8, value=f"=SUM(H5:H{start_row-1})")
        c_tot_m.number_format = '$#,##0'
        c_tot_m.font = bold_font
        
        c_tot_pct = ws.cell(row=start_row, column=9, value=f"=H{start_row}/F{start_row}")
        c_tot_pct.number_format = '0.0%'
        c_tot_pct.font = bold_font

        for c in range(1, 10):
            cell = ws.cell(row=start_row, column=c)
            cell.border = total_border
            cell.fill = total_fill

        # Auto-adjust column widths
        for col in ws.columns:
            max_len = 0
            col_letter = get_column_letter(col[0].column)
            for cell in col:
                val_str = str(cell.value or '')
                if cell.number_format and '$' in cell.number_format:
                    val_str += "   "
                if len(val_str) > max_len:
                    max_len = len(val_str)
            ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        wb.save(output_path)
        return output_path


class EmployeeDocumentEngine:
    """Creates formatted Word (.docx) commercial proposals and executive briefs."""

    @staticmethod
    def create_tour_commercial_proposal(output_path: str, client_name: str = "Катенька Gwaladze / Tour Partners 2027") -> str:
        doc = docx.Document()

        # Page margins
        for section in doc.sections:
            section.top_margin = Inches(1)
            section.bottom_margin = Inches(1)
            section.left_margin = Inches(1)
            section.right_margin = Inches(1)

        # Title
        p_title = doc.add_paragraph()
        p_title.paragraph_format.space_before = Pt(0)
        p_title.paragraph_format.space_after = Pt(4)
        run_title = p_title.add_run("GEORGIA EXPEDITIONS 2027")
        run_title.font.name = "Calibri"
        run_title.font.size = Pt(24)
        run_title.font.bold = True
        run_title.font.color.rgb = RGBColor(0x1F, 0x29, 0x37)

        # Subtitle
        p_sub = doc.add_paragraph()
        p_sub.paragraph_format.space_after = Pt(18)
        run_sub = p_sub.add_run(f"Comprehensive Commercial Proposal & Tour Blueprint • Prepared for {client_name}")
        run_sub.font.name = "Calibri"
        run_sub.font.size = Pt(12)
        run_sub.font.color.rgb = RGBColor(0x4B, 0x55, 0x63)

        # Divider
        p_div = doc.add_paragraph()
        p_div.paragraph_format.space_after = Pt(14)
        run_div = p_div.add_run("―" * 48)
        run_div.font.color.rgb = RGBColor(0xD1, 0xD5, 0xDB)

        # Executive Summary
        h1 = doc.add_heading("1. Executive Summary", level=1)
        h1.paragraph_format.space_before = Pt(12)
        h1.paragraph_format.space_after = Pt(6)

        p_exec = doc.add_paragraph(
            "Georgia in 2027 stands at the apex of global travel interest: an unmatched convergence of 8,000 years of unbroken winemaking heritage, UNESCO ancient Svanetian towers, dramatic Caucasus peaks, and a booming culinary hospitality scene. This document outlines our turnkey 2027 travel portfolio designed for high-value cultural immersion, private small groups, and robust gross profit margins (48-52%)."
        )
        p_exec.paragraph_format.line_spacing = 1.15
        p_exec.paragraph_format.space_after = Pt(12)

        # Key Tour Pillars
        h2 = doc.add_heading("2. Core 2027 Tour Offerings", level=1)
        h2.paragraph_format.space_before = Pt(14)
        h2.paragraph_format.space_after = Pt(6)

        offerings = [
            ("Grand Georgia 10-Day Odyssey", "Full spectrum route spanning Tbilisi Old Town, Kakheti wine valleys, Kazbegi / Gergeti Trinity Church, and Batumi Black Sea boulevard."),
            ("Wine & Gastronomy Masterclass (6 Days)", "Exclusive private tastings at qvevri natural wineries, masterclasses with renowned Georgian chefs, and stay in chateau boutique estates."),
            ("High Caucasus Mountain Expedition (7 Days)", "Jeep & hiking journey through the dramatic Truso Valley, Ushguli (highest inhabited European village), and Svaneti defensive towers."),
            ("Weekend City & Thermal Retreat (4 Days)", "Curated Tbilisi art galleries, Fabrika creative cluster, sulfur bath rituals, and modern Georgian fine dining.")
        ]

        for name, desc in offerings:
            p = doc.add_paragraph(style='List Bullet')
            p.paragraph_format.space_after = Pt(4)
            r_bold = p.add_run(f"{name}: ")
            r_bold.font.bold = True
            p.add_run(desc)

        # Financial Summary Table
        h3 = doc.add_heading("3. Financial & Margin Breakdown", level=1)
        h3.paragraph_format.space_before = Pt(14)
        h3.paragraph_format.space_after = Pt(8)

        table = doc.add_table(rows=1, cols=4)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = False

        headers = ["Tour Package", "Retail Price / Pax", "Net Cost / Pax", "Target Gross Margin"]
        hdr_cells = table.rows[0].cells
        for i, title in enumerate(headers):
            hdr_cells[i].text = title
            hdr_cells[i].paragraphs[0].runs[0].font.bold = True
            hdr_cells[i].paragraphs[0].runs[0].font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            # Background shading via raw XML
            shading_elm = docx.oxml.parse_xml(r'<w:shd {} w:fill="1F2937"/>'.format(docx.oxml.ns.nsdecls('w')))
            hdr_cells[i]._tc.get_or_add_tcPr().append(shading_elm)

        data = [
            ("Grand Georgia 10-Day", "$2,690", "$1,350", "49.8% ($1,340)"),
            ("Wine & Gastronomy 6-Day", "$2,250", "$1,100", "51.1% ($1,150)"),
            ("High Caucasus 7-Day", "$1,750", "$850", "51.4% ($900)"),
            ("Tbilisi Arts 4-Day", "$990", "$480", "51.5% ($510)"),
        ]

        for row in data:
            row_cells = table.add_row().cells
            for i, text in enumerate(row):
                row_cells[i].text = text
                if i >= 1:
                    row_cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.RIGHT

        # Add space after table
        p_sp = doc.add_paragraph()
        p_sp.paragraph_format.space_after = Pt(12)

        # Strategic Next Steps
        h4 = doc.add_heading("4. Implementation Roadmap", level=1)
        h4.paragraph_format.space_before = Pt(14)
        h4.paragraph_format.space_after = Pt(6)

        steps = [
            ("Q1 2026", "Finalize partner agreements with boutique hotels in Kakheti & Kazbegi."),
            ("Q2 2026", "Launch digital marketing campaign and website booking portal."),
            ("Q3 2026", "Pre-book peak season allocations (September grape harvest / Rtveli)."),
            ("Q1 2027", "Begin departures for the 2027 season.")
        ]

        for q, desc in steps:
            p = doc.add_paragraph(style='List Number')
            p.paragraph_format.space_after = Pt(4)
            r_q = p.add_run(f"[{q}] ")
            r_q.font.bold = True
            p.add_run(desc)

        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        doc.save(output_path)
        return output_path


