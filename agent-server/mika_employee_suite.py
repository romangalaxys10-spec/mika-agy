class EmployeeWorkspaceManager:
    """Creates organized project packages on macOS Desktop and bundles all deliverables."""

    @staticmethod
    def setup_project_workspace(project_name: str = "Georgia_Tours_2027_Project") -> str:
        desktop = os.path.expanduser("~/Desktop")
        project_dir = os.path.join(desktop, project_name)
        os.makedirs(project_dir, exist_ok=True)
        os.makedirs(os.path.join(project_dir, "Presentations"), exist_ok=True)
        os.makedirs(os.path.join(project_dir, "Financial_Models"), exist_ok=True)
        os.makedirs(os.path.join(project_dir, "Proposals_and_Docs"), exist_ok=True)
        os.makedirs(os.path.join(project_dir, "Research_Notes"), exist_ok=True)
        return project_dir


